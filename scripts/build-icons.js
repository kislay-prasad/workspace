// Builds public/js/icons.js from the Fluent UI System Icons package (MIT, Microsoft), the icon family Microsoft Teams uses.
//   npm pack @fluentui/svg-icons && tar -xzf fluentui-svg-icons-*.tgz
//   node scripts/build-icons.js path/to/package/icons
const fs = require('fs');
const path = require('path');

const REGULAR = `add alert alert_off archive archive_arrow_back arrow_down arrow_up arrow_left arrow_reply arrow_forward arrow_download arrow_minimize arrow_maximize arrow_exit
attach bookmark bookmark_off broom calendar_ltr calendar_arrow_right calendar_clock call call_end camera chat chat_multiple checkmark checkmark_circle chevron_down chevron_right
chevron_left chevron_up circle clock color comment compose copy database delete desktop dismiss document document_pdf door_arrow_right edit emoji emoji_add eye eye_off
filter folder folder_zip full_screen_maximize full_screen_minimize games globe grid hand_right history hourglass_half image info keyboard link lightbulb lock_closed mail_read
megaphone mic mic_off more_horizontal more_vertical music_note_2 navigation note open paint_brush people people_add people_team person person_add person_delete person_edit pin pin_off
poll prohibited qr_code record search send send_clock settings share_screen_start share_screen_stop shield shield_person shield_lock sign_out speaker_2 speaker_mute star star_off
sticker stethoscope tag task_list_ltr timer video video_off warning whiteboard window wrench animal_turtle question_circle arrow_sync text_edit_style slide_text
eraser arrow_undo play people_list presenter picture_in_picture_exit layout_column_two arrow_expand speaker_0 apps cast desktop_arrow_right
arrow_enter dismiss_circle record_stop`.split(/\s+/).filter(Boolean);
const FILLED = `chat alert call bookmark people_team calendar_ltr settings shield_person hand_right star send pin mic mic_off video video_off call_end share_screen_start people info
checkmark_circle circle record people_list presenter`.split(/\s+/).filter(Boolean);
const PRESENCE = [['presence_available', 'filled'], ['presence_away', 'filled'], ['presence_dnd', 'filled'], ['presence_busy', 'filled'], ['presence_offline', 'regular']];

const dir = process.argv[2]; if (!dir) { console.error('usage: node scripts/build-icons.js <icons dir>'); process.exit(1); }
const inner = (file) => { const s = fs.readFileSync(path.join(dir, file), 'utf8').trim(); const m = /^<svg[^>]*viewBox="0 0 (\d+) \d+"[^>]*>([\s\S]*)<\/svg>$/.exec(s); if (!m) throw new Error('unexpected svg ' + file); return [Number(m[1]), m[2]]; };
const out = {};
for (const n of REGULAR) out[n] = inner(`${n}_20_regular.svg`);
for (const n of FILLED) out[n + '~f'] = inner(`${n}_20_filled.svg`);
for (const [n, v] of PRESENCE) out[n] = inner(`${n}_12_${v}.svg`);
const body = `'use strict';
// Icons: Fluent UI System Icons (https://github.com/microsoft/fluentui-system-icons) — MIT License, Copyright (c) 2020 Microsoft Corporation.
// The same icon family Microsoft Teams uses. Generated by scripts/build-icons.js; do not edit by hand.
(() => {
  const LC = (window.LC = window.LC || {});
  const I = ${JSON.stringify(out)};
  const NS = 'http://www.w3.org/2000/svg', cache = new Map();
  // LC.icon('call') -> <svg class="ic">; { filled: true } for the solid variant, { cls } adds classes, { label } makes it announced
  LC.icon = (name, o = {}) => {
    const key = o.filled && I[name + '~f'] ? name + '~f' : name; let tpl = cache.get(key);
    if (!tpl) {
      const src = I[key] || I.circle; tpl = document.createElementNS(NS, 'svg');
      tpl.setAttribute('viewBox', \`0 0 \${src[0]} \${src[0]}\`); tpl.setAttribute('fill', 'currentColor'); tpl.setAttribute('focusable', 'false'); tpl.setAttribute('class', 'ic');
      const doc = new DOMParser().parseFromString(\`<svg xmlns="\${NS}">\${src[1]}</svg>\`, 'image/svg+xml');
      for (const n of [...doc.documentElement.childNodes]) tpl.appendChild(document.importNode(n, true));
      cache.set(key, tpl);
    }
    const svg = tpl.cloneNode(true); if (o.cls) svg.setAttribute('class', 'ic ' + o.cls);
    if (o.label) { svg.setAttribute('role', 'img'); svg.setAttribute('aria-label', o.label); } else svg.setAttribute('aria-hidden', 'true');
    return svg;
  };
  LC.hasIcon = (name) => !!I[name];
})();
`;
fs.writeFileSync(path.join(__dirname, '..', 'public', 'js', 'icons.js'), body);
console.log('icons.js:', Object.keys(out).length, 'icons,', Math.round(body.length / 1024), 'KB');
